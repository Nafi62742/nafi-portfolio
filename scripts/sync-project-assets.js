const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.resolve(__dirname, '..');
const PROJECTS_ASSETS_DIR = path.join(ROOT_DIR, 'src', 'assets', 'images', 'projects');
const RUNMATE_ASSETS_DIR = path.join(ROOT_DIR, 'src', 'assets', 'images', 'runmate');
const OUTPUT_TS_FILE = path.join(ROOT_DIR, 'src', 'app', 'utils', 'project-assets.generated.ts');
const OUTPUT_JSON_FILE = path.join(ROOT_DIR, 'src', 'assets', 'project-gallery-manifest.json');

const IMAGE_EXTENSIONS = new Set(['.png', '.jpg', '.jpeg', '.webp', '.svg', '.gif', '.avif']);

const ALIASES = {
  keiai: ['keiai', 'keiaiorderapp'],
  petapp: ['petapp', 'pet', 'petauctionapp'],
  gramstain: ['gramstain', 'gramstainatlas'],
  flourtopastry: ['flourtopastry', 'flourtopastrycake'],
  getfund: ['getfund'],
  schoolmanagementsystem: ['schoolmanagementsystem'],
  recklessseas: ['recklessseas'],
  koyama: ['koyama', 'koyamashokai'],
  izumi: ['izumi'],
  ginsen: ['ginsen'],
  voicerecord: ['voicerecord', 'voicerecordandplayer', 'voicerecordplay', 'voicerecordplayer'],
  pabokothay: ['pabokothay'],
  nearestlocation: ['nearestlocation', 'nearestareafinder', 'nearestarea'],
  runmate: ['runmate', 'runmateclub']
};

/**
 * Normalizes a string to a lowercase alphanumeric key.
 */
function normalizeKey(str) {
  return str.toLowerCase().replace(/[^a-z0-9]/g, '');
}

/**
 * Recursively scans directory for image files.
 */
function getImagesInDir(dirPath, relativePrefix) {
  if (!fs.existsSync(dirPath)) return [];
  const entries = fs.readdirSync(dirPath, { withFileTypes: true });
  const images = [];

  for (const entry of entries) {
    if (entry.isFile()) {
      const ext = path.extname(entry.name).toLowerCase();
      if (IMAGE_EXTENSIONS.has(ext)) {
        images.push(`${relativePrefix}/${entry.name}`);
      }
    }
  }

  // Sort files naturally (e.g., slide_1 before slide_2)
  return images.sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }));
}

function syncProjectAssets() {
  const mapping = {};

  // Ensure known directories exist so the user can easily drop images in
  const knownFolders = [
    'flourtopastry', 'getfund', 'gramstain', 'izumi', 'keiai',
    'koyama', 'nearestlocation', 'pabokothay', 'petapp',
    'recklessseas', 'schoolmanagementsystem', 'voicerecord', 'ginsen'
  ];
  for (const f of knownFolders) {
    const p = path.join(PROJECTS_ASSETS_DIR, f);
    if (!fs.existsSync(p)) {
      fs.mkdirSync(p, { recursive: true });
    }
  }

  // 1. Scan src/assets/images/projects subdirectories
  if (fs.existsSync(PROJECTS_ASSETS_DIR)) {
    const folders = fs.readdirSync(PROJECTS_ASSETS_DIR, { withFileTypes: true });
    for (const folder of folders) {
      if (folder.isDirectory()) {
        const folderName = folder.name;
        const folderPath = path.join(PROJECTS_ASSETS_DIR, folderName);
        const relativePrefix = `assets/images/projects/${folderName}`;
        const images = getImagesInDir(folderPath, relativePrefix);
        const key = normalizeKey(folderName);
        mapping[key] = images;

        // Apply aliases
        if (ALIASES[key]) {
          for (const alias of ALIASES[key]) {
            mapping[normalizeKey(alias)] = images;
          }
        }
      }
    }
  }

  // 2. Scan src/assets/images/runmate directory
  if (fs.existsSync(RUNMATE_ASSETS_DIR)) {
    const runmateImages = getImagesInDir(RUNMATE_ASSETS_DIR, 'assets/images/runmate');
    mapping['runmate'] = runmateImages;
    mapping['runmateclub'] = runmateImages;
  }

  // Generate TypeScript code
  const tsContent = `// ─── Auto-generated by scripts/sync-project-assets.js ────────────────────────
// DO NOT EDIT MANUALLY. Add or remove images in src/assets/images/projects/<folder>/
// and run 'npm run sync:assets' (or start/build the app) to update this file.

/**
 * Mapping of normalized project keys to their dynamically discovered screenshot assets.
 */
export const PROJECT_GALLERY_ASSETS: Record<string, string[]> = ${JSON.stringify(mapping, null, 2)};

/**
 * Retrieves all available image screenshot paths for a given project key, folder, or name.
 *
 * @param key - The project name, folder name, or slug (e.g. 'pet-app', 'Pet App', 'keiai')
 * @returns Array of relative asset image paths
 */
export function getProjectScreenshots(key: string): string[] {
  if (!key) return [];
  const normalizedKey = key.toLowerCase().replace(/[^a-z0-9]/g, '');
  return PROJECT_GALLERY_ASSETS[normalizedKey] || [];
}
`;

  // Write TypeScript file
  fs.mkdirSync(path.dirname(OUTPUT_TS_FILE), { recursive: true });
  fs.writeFileSync(OUTPUT_TS_FILE, tsContent, 'utf-8');

  // Write JSON manifest file
  fs.mkdirSync(path.dirname(OUTPUT_JSON_FILE), { recursive: true });
  fs.writeFileSync(OUTPUT_JSON_FILE, JSON.stringify(mapping, null, 2), 'utf-8');

  console.log('✅ Project assets synchronized successfully.');
}

syncProjectAssets();
